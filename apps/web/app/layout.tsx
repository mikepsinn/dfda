// On a company instance, the tab title and description use its name and tagline.
export async function generateMetadata(): Promise<Metadata> {
  const instance = await resolveInstance()
  if (!instance) return baseMetadata
  return {
    ...baseMetadata,
    title: instance.name,
    description: instance.tagline ?? baseMetadata.description,
    openGraph: { ...baseMetadata.openGraph, title: instance.name, siteName: instance.name },
    twitter: { ...baseMetadata.twitter, title: instance.name },
  }
}

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode
}>) {
  const user = await getServerUser()
  let profile: Profile | null = null

  if (user) {
    profile = await getProfileByIdAction(user.id)
  }
  // A company instance (its own domain, subdomain or preview link) is the company's own site:
  // its branding, header and footer, and only its pages (lib/instance/routes.ts).
  const instance = await resolveInstance()

  return (
    <html lang="en" className={cn(inter.variable, instance && isDark(instance.backgroundColor) && DARK_CLASS)}>
      {/* An instance sets its font in InstanceTheme. */}
      <body className={instance ? undefined : inter.className}>
        {instance && <InstanceTheme theme={instance} />}
        {instance?.via === "preview" && <PreviewBar name={instance.name} />}
        <TooltipProvider>
          <ScrollToHashElement />
          <SiteChrome
            header={
              instance ? (
                <InstanceHeader brand={instance} initialUser={user} initialProfile={profile} />
              ) : (
                <Header initialUser={user} initialProfile={profile} siteName={env.NEXT_PUBLIC_SITE_NAME} />
              )
            }
            footer={
              instance ? (
                <InstanceFooter
                  brand={instance}
                  // In a preview, the network's site is on this host: the link ends the preview first.
                  network={{ name: env.NEXT_PUBLIC_SITE_NAME, url: instance.via === "preview" ? "/i" : env.NEXT_PUBLIC_SITE_URL }}
                />
              ) : (
                <Footer siteName={env.NEXT_PUBLIC_SITE_NAME} />
              )
            }
          >
            {children}
          </SiteChrome>
          <Toaster />
        </TooltipProvider>
      </body>
    </html>
  )
}



